/**
 * Prints the scenario tables (presets × racks, tornado, break-evens) and writes docs/findings-tables.md.
 * Every number comes from data/assumptions.json + the engine.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  applyPreset, breakevens, curveFor, defaultSettings, demandShare, evaluate, fmtIrr, fmtPayback, fmtPct, fmtTokens,
  fmtUsd, fmtUsdPerM, impliedTps, inputsFromSettings, sensitivity, type Assumptions, type RackId, type ScenarioPresetId,
} from '@gpu-roi/engine';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const A = JSON.parse(readFileSync(resolve(root, 'data/assumptions.json'), 'utf8')) as Assumptions;
const anchors = { openrouterTokensPerDay: A.anchors.openrouterTokensPerDay.value, deepseekTokensPerDay: A.anchors.deepseekTokensPerDay.value };

type Row = string[];
const md = (head: Row, rows: Row[]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');

const out: string[] = [];
out.push(`# Scenario tables (generated)\n\nGenerated by \`npm run scenario\` from \`data/assumptions.json\` (version ${A.version}). One rack. Do not edit by hand.\n`);

// 1. Presets × racks
const head = ['Scenario', 'Rack', 'Speed tok/s/user', 'tok/s/GPU', 'Output/day', 'Revenue/day', 'Electricity/day', 'Cash margin', 'Op. margin', 'Payback', 'NPV', 'IRR', 'Full cost $/M out', '$/GPU-hr'];
const rows: Row[] = [];
for (const p of ['pitch', 'realistic', 'bear'] as ScenarioPresetId[]) {
  for (const rack of ['gb200', 'gb300'] as RackId[]) {
    const s = applyPreset(A, { ...defaultSettings(A), rack }, p);
    const i = inputsFromSettings(A, s);
    const { daily: d, schedule: sc } = evaluate(i, curveFor(A, rack));
    rows.push([
      A.presets[p].label, A.racks[rack].label, String(i.interactivity), d.tpsPerGpu.toFixed(0), fmtTokens(d.outputTokens),
      fmtUsd(d.revenueUsd), fmtUsd(d.electricityUsd), fmtPct(d.cashMargin), fmtPct(d.operatingMargin),
      fmtPayback(sc.paybackMonth, sc.months), fmtUsd(sc.npvUsd), fmtIrr(sc.irr), fmtUsdPerM(d.fullCostPerMOut), `$${d.revenuePerGpuHr.toFixed(2)}`,
    ]);
  }
}
out.push('## Presets\n');
out.push('Pitch: benchmark-best speed, 100% of benchmark throughput, 100% utilization, Z.ai list price, no price decline. Realistic: 100 tok/s per user, 50% achieved, 60% utilization, market floor, prices −50%/yr. Bear: 25% achieved, 40% utilization, half the floor, −70%/yr.\n');
out.push(md(head, rows));

// 2. Realistic details on GB200
const i0 = inputsFromSettings(A, defaultSettings(A));
const c0 = curveFor(A, 'gb200');
const r0 = evaluate(i0, c0);
const d0 = r0.daily;
const ds = demandShare(d0, anchors);
const be = breakevens(i0, c0);
out.push('\n## Realistic case, GB200: cost stack per day\n');
out.push(md(['Item', 'Per day', 'Per M output tokens'], [
  ['Electricity', fmtUsd(d0.electricityUsd), fmtUsdPerM(d0.electricityUsd / (d0.outputTokens / 1e6))],
  ['Colocation', fmtUsd(d0.coloUsd), fmtUsdPerM(d0.coloUsd / (d0.outputTokens / 1e6))],
  ['Other opex', fmtUsd(d0.otherOpexUsd), fmtUsdPerM(d0.otherOpexUsd / (d0.outputTokens / 1e6))],
  ['Depreciation', fmtUsd(d0.depreciationUsd), fmtUsdPerM(d0.depreciationUsd / (d0.outputTokens / 1e6))],
  ['Total', fmtUsd(d0.cashCostUsd + d0.depreciationUsd), fmtUsdPerM(d0.fullCostPerMOut)],
  ['Revenue (output / input)', `${fmtUsd(d0.outputRevenueUsd)} / ${fmtUsd(d0.inputRevenueUsd)}`, ''],
]));
out.push(`\nDemand: ${fmtTokens(ds.tokensPerDay)} tokens/day (output + input) = ${fmtPct(ds.shareOfOpenRouter)} of OpenRouter's daily volume, ${fmtPct(ds.shareOfDeepSeek2025)} of DeepSeek's Feb-2025 daily volume.`);
out.push(`\nBreak-evens: all token prices can fall to ${fmtPct(be.priceLevel)} of today's (output ${fmtUsdPerM(be.outPriceUsdPerM)}/M) before operating profit is zero; utilization for payback within life ${fmtPct(be.utilizationForPaybackAtLife)}; price decline at which NPV = 0: ${be.priceDeclineForZeroNpv === null ? 'none (NPV < 0 at flat prices)' : (be.priceDeclineForZeroNpv >= 0.98 ? '≥98' : fmtPct(be.priceDeclineForZeroNpv).replace('%', '')) + '%/yr'}.`);

// 3. Tornado
out.push('\n## Sensitivity at realistic defaults, GB200 (NPV at 7%, ranked by swing)\n');
out.push(md(['Input', 'Low', 'NPV low', 'Payback low', 'High', 'NPV high', 'Payback high'],
  sensitivity(i0, c0).map((r) => [r.label, r.lowLabel, fmtUsd(r.lowNpv), fmtPayback(r.lowPayback, r0.schedule.months), r.highLabel, fmtUsd(r.highNpv), fmtPayback(r.highPayback, r0.schedule.months)])));

// 4. Frontier: payback by utilization × decline
out.push('\n## Payback frontier, GB200, realistic otherwise (rows utilization, columns price decline per year)\n');
const declines = [0, 0.3, 0.5, 0.7, 0.8, 0.9];
const fr: Row[] = [];
for (const u of [0.1, 0.2, 0.3, 0.4, 0.6, 0.8, 1]) {
  fr.push([fmtPct(u), ...declines.map((dcl) => {
    const s = evaluate({ ...i0, utilization: u, priceDeclinePerYear: dcl }, c0).schedule;
    return fmtPayback(s.paybackMonth, s.months);
  })]);
}
out.push(md(['Util \\ decline', ...declines.map((x) => `${Math.round(x * 100)}%`)], fr));

// 5. Claim check
const c = A.anchors.nvidiaClaim;
out.push(`\n## NVIDIA claim check\n\n$${c.capexUsd / 1e6}M → $${c.revenueUsd / 1e6}M over ${c.years} years at $${c.priceOutUsdPerM}/M output tokens needs ${impliedTps(c.revenueUsd / c.years, c.priceOutUsdPerM, c.gpus).toFixed(0)} output tok/s per GPU sustained 24×7, output revenue only. Realistic case delivers ${(d0.tpsPerGpu * i0.utilization).toFixed(0)} sold tok/s per GPU.`);

const text = out.join('\n') + '\n';
writeFileSync(resolve(root, 'docs/findings-tables.md'), text);
console.log(text);
