/**
 * Prints the scenario tables (one-day ledger, presets × racks, tornado, break-evens) and writes docs/findings-tables.md.
 * Every number comes from data/assumptions.json + the engine.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  applyPreset, breakevens, curveFor, defaultSettings, demandShare, evaluate, fmtIrr, fmtPayback, fmtPct, fmtTokens,
  fmtUsd, fmtUsdPerM, impliedTps, inputsFromSettings, sensitivity, type Assumptions, type RackId, type ScenarioPresetId, type Tenure,
} from '@gpu-roi/engine';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const A = JSON.parse(readFileSync(resolve(root, 'data/assumptions.json'), 'utf8')) as Assumptions;
const anchors = { openrouterTokensPerDay: A.anchors.openrouterTokensPerDay.value, deepseekTokensPerDay: A.anchors.deepseekTokensPerDay.value };

type Row = string[];
const md = (head: Row, rows: Row[]) =>
  [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const base = defaultSettings(A);
const run = (tenure: Tenure, rack: RackId, over: Partial<typeof base> = {}) => {
  const s = { ...base, ...over, tenure, rack };
  const i = inputsFromSettings(A, s);
  return { s, i, ...evaluate(i, curveFor(A, rack)) };
};

const out: string[] = [];
out.push(`# Scenario tables (generated)\n\nGenerated by \`npm run scenario\` from \`data/assumptions.json\` (version ${A.version}). One rack. Do not edit by hand.\n`);

// 0. One day, one rack: the four questions
out.push('## One GB200 NVL72 rack, one day, GLM-5.3 (FP4) at 95 tok/s per user, median FP4 price, OpenRouter token mix\n');
out.push('Capacity is InferenceX AgentX output per GPU, prefill GPUs included, adjusted to OpenRouter\'s prefill load. "Realistic" = 70% of capacity sold. "Peak" = 100% sold.\n');
const ledger: Row[] = [];
for (const [label, over] of [['Realistic', {}], ['Peak', { utilization: 1 }]] as Array<[string, Partial<typeof base>]>) {
  for (const t of ['rent', 'own'] as Tenure[]) {
    const { i, daily: d, schedule: sc } = run(t, 'gb200', over);
    ledger.push([
      `${label}, ${t}`,
      t === 'rent' ? `${fmtUsd(d.rentUsd)} (rent $${i.rentUsdPerGpuHr}/GPU-hr)` : `${fmtUsd(d.costUsd)} (power ${fmtUsd(d.electricityUsd)}, colo ${fmtUsd(d.coloUsd)}, opex ${fmtUsd(d.otherOpexUsd)}, depreciation ${fmtUsd(d.depreciationUsd)})`,
      `${fmtTokens(d.outputTokens)} out + ${fmtTokens(d.inputTokens)} in`,
      fmtUsd(d.revenueUsd),
      `${fmtUsd(d.operatingProfitUsd)} (${fmtPct(d.operatingMargin)})`,
      t === 'rent' ? (sc.underwaterMonth === null ? 'covers rent all 4 yr' : `stops covering rent in month ${sc.underwaterMonth}`) : `payback ${fmtPayback(sc.paybackMonth, sc.months)}, NPV ${fmtUsd(sc.npvUsd)}`,
    ]);
  }
}
out.push(md(['Case', 'Cost / day', 'Tokens / day', 'Revenue / day', 'Profit / day', 'Over time (prices −50%/yr)'], ledger));
{
  const r = run('rent', 'gb200');
  const o = run('own', 'gb200');
  const br = breakevens(r.i, curveFor(A, 'gb200'));
  const bo = breakevens(o.i, curveFor(A, 'gb200'));
  out.push(`\nBreak-even share of capacity sold: renting on demand ${fmtPct(br.soldShareToBreakEven)}, owning ${fmtPct(bo.soldShareToBreakEven)}. Revenue per GPU-hour ${'$' + r.daily.revenuePerGpuHr.toFixed(2)} against rent of $${r.i.rentUsdPerGpuHr} and an owning cost of $${(o.daily.costUsd / (o.daily.gpus * 24)).toFixed(2)}.`);
}

// 1. Presets × racks × tenure
const head = ['Scenario', 'Rack', 'Tenure', 'Speed tok/s/user', 'Capacity tok/s/GPU', 'Sold tok/s/GPU', 'Output/day', 'Revenue/day', 'Cost/day', 'Profit/day', 'Margin', 'Payback', 'Underwater', 'NPV', '$/GPU-hr'];
const rows: Row[] = [];
for (const p of ['pitch', 'realistic', 'bear'] as ScenarioPresetId[]) {
  for (const rack of ['gb200', 'gb300'] as RackId[]) {
    for (const t of ['rent', 'own'] as Tenure[]) {
      const s = applyPreset(A, { ...base, rack, tenure: t }, p);
      const i = inputsFromSettings(A, s);
      const { daily: d, schedule: sc } = evaluate(i, curveFor(A, rack));
      rows.push([
        A.presets[p].label, A.racks[rack].label, t, String(i.interactivity), d.capacityPerGpu.toFixed(0), (d.tpsPerGpu * i.utilization).toFixed(0), fmtTokens(d.outputTokens),
        fmtUsd(d.revenueUsd), fmtUsd(d.costUsd), fmtUsd(d.operatingProfitUsd), fmtPct(d.operatingMargin),
        t === 'own' ? fmtPayback(sc.paybackMonth, sc.months) : 'n/a', sc.underwaterMonth === null ? '—' : `month ${sc.underwaterMonth}`, fmtUsd(sc.npvUsd), `$${d.revenuePerGpuHr.toFixed(2)}`,
      ]);
    }
  }
}
out.push('\n## Presets\n');
out.push('Pitch: fastest measured throughput, 100% sold, Z.ai list price, no price decline. Realistic: 95 tok/s per user, 70% sold, median FP4 price, prices −50%/yr. Bear: 80% of measured throughput, 50% sold, DeepInfra\'s discounted price, −70%/yr. Rent is on demand. A renter hands the rack back the month it stops covering rent, so rent NPVs are the profit banked before that.\n');
out.push(md(head, rows));

// 2. Realistic details on GB200, owning
const o0 = run('own', 'gb200');
const i0 = o0.i;
const c0 = curveFor(A, 'gb200');
const d0 = o0.daily;
const ds = demandShare(d0, anchors);
const be = breakevens(i0, c0);
out.push('\n## Realistic case, GB200, owning: cost stack per day\n');
out.push(md(['Item', 'Per day', 'Per M output tokens'], [
  ['Electricity', fmtUsd(d0.electricityUsd), fmtUsdPerM(d0.electricityUsd / (d0.outputTokens / 1e6))],
  ['Colocation', fmtUsd(d0.coloUsd), fmtUsdPerM(d0.coloUsd / (d0.outputTokens / 1e6))],
  ['Other opex', fmtUsd(d0.otherOpexUsd), fmtUsdPerM(d0.otherOpexUsd / (d0.outputTokens / 1e6))],
  ['Depreciation', fmtUsd(d0.depreciationUsd), fmtUsdPerM(d0.depreciationUsd / (d0.outputTokens / 1e6))],
  ['Total', fmtUsd(d0.costUsd), fmtUsdPerM(d0.fullCostPerMOut)],
  ['Revenue (output / input)', `${fmtUsd(d0.outputRevenueUsd)} / ${fmtUsd(d0.inputRevenueUsd)}`, ''],
]));
out.push(`\nDemand: ${fmtTokens(ds.tokensPerDay)} tokens/day (output + input) = ${fmtPct(ds.shareOfOpenRouter)} of OpenRouter's daily volume, ${fmtPct(ds.shareOfDeepSeek2025)} of DeepSeek's Feb-2025 daily volume.`);
out.push(`\nBreak-evens (owning): all token prices can fall to ${fmtPct(be.priceLevel)} of today's (output ${fmtUsdPerM(be.outPriceUsdPerM)}/M) before operating profit is zero; share sold for payback within life ${fmtPct(be.utilizationForPaybackAtLife)}; price decline at which NPV = 0: ${be.priceDeclineForZeroNpv === null ? 'none (NPV < 0 at flat prices)' : (be.priceDeclineForZeroNpv >= 0.98 ? '≥98' : fmtPct(be.priceDeclineForZeroNpv).replace('%', '')) + '%/yr'}.`);

// 3. Tornado, both tenures
for (const t of ['rent', 'own'] as Tenure[]) {
  const r = run(t, 'gb200');
  out.push(`\n## Sensitivity at realistic defaults, GB200, ${t} (ranked by NPV swing)\n`);
  out.push(md(['Input', 'Low', 'Profit/day low', 'NPV low', 'High', 'Profit/day high', 'NPV high'],
    sensitivity(r.i, c0).map((x) => [x.label, x.lowLabel, fmtUsd(x.lowProfit), fmtUsd(x.lowNpv), x.highLabel, fmtUsd(x.highProfit), fmtUsd(x.highNpv)])));
}

// 4. Frontier: payback by utilization × decline (owning)
out.push('\n## Payback frontier, GB200, owning, realistic otherwise (rows share sold, columns price decline per year)\n');
const declines = [0, 0.3, 0.5, 0.7, 0.8, 0.9];
const fr: Row[] = [];
for (const u of [0.1, 0.2, 0.3, 0.4, 0.6, 0.8, 1]) {
  fr.push([fmtPct(u), ...declines.map((dcl) => {
    const s = evaluate({ ...i0, utilization: u, priceDeclinePerYear: dcl }, c0).schedule;
    return fmtPayback(s.paybackMonth, s.months);
  })]);
}
out.push(md(['Sold \\ decline', ...declines.map((x) => `${Math.round(x * 100)}%`)], fr));

// 5. Claim check
const c = A.anchors.nvidiaClaim;
const peak = run('own', 'gb200', { achieved: 1, utilization: 1 }).daily;
out.push(`\n## NVIDIA claim check\n\n$${c.capexUsd / 1e6}M → $${c.revenueUsd / 1e6}M over ${c.years} years at $${c.priceOutUsdPerM}/M output tokens needs ${impliedTps(c.revenueUsd / c.years, c.priceOutUsdPerM, c.gpus).toFixed(0)} output tok/s per GPU sustained 24×7, output revenue only. At the default speed the rack's capacity with prefill counted is ${peak.capacityPerGpu.toFixed(0)} tok/s per GPU; the realistic case sells ${(d0.tpsPerGpu * i0.utilization).toFixed(0)}.`);

const text = out.join('\n') + '\n';
writeFileSync(resolve(root, 'docs/findings-tables.md'), text);
console.log(text);
